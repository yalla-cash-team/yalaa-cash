/// Structural URL rules for banner links: http/https with a host only. No
/// file extension is required, and query strings (including signed CDN
/// parameters) are kept as-is. Unsafe schemes such as javascript: or file:
/// are rejected by the protocol allow-list.
const BANNER_URL_OPTIONS = {
  protocols: ["http", "https"],
  require_protocol: true,
  require_tld: false,
};

export class CreateBannerDto {
  @IsString()
  @MinLength(2)
  @MaxLength(120)
  title!: string;

  @IsOptional()
  @IsString()
  @MaxLength(180)
  subtitle?: string;

  @IsString()
  @MaxLength(2048)
  // Structural validation only (scheme http/https + non-empty host) — never
  // requires a file extension, matching the Admin Flutter validation.
  @IsUrl(BANNER_URL_OPTIONS, {
    message: "imageUrl must be a valid http:// or https:// URL.",
  })
  imageUrl!: string;

  @IsOptional()
  @IsString()
  @MaxLength(2048)
  @IsUrl(BANNER_URL_OPTIONS, {
    message: "targetUrl must be a valid http:// or https:// URL.",
  })
  targetUrl?: string;

  @IsOptional()
  @IsEnum(BannerPlacement)
  placement?: BannerPlacement;

  @IsOptional()
  @IsEnum(BannerStyle)
  style?: BannerStyle;

  @IsOptional()
  @IsBoolean()
  isActive?: boolean;

  @IsInt()
  @Min(0)
  displayOrder!: number;

  @IsOptional()
  @IsDateString()
  startsAt?: string;

  @IsOptional()
  @IsDateString()
  endsAt?: string;

  @IsOptional()
  @IsString()
  governorateId?: string;
}

